def csv(path,rows):
    path=Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    frame=rows if isinstance(rows,pd.DataFrame) else pd.DataFrame(rows)
    temporary=path.with_suffix(".tmp.csv")
    frame.to_csv(temporary,index=False)
    temporary.replace(path)
    return frame


def latex_table(frame,path,caption,label):
    body=frame.to_latex(index=False,escape=True,float_format=lambda x:f"{x:.4f}")
    Path(path).write_text("% Generated by python -m dcl.paperstudy.report; do not hand edit.\n"
       "\\begin{table}[t]\\centering\\small\n"+body+
       "\\caption{"+caption+"}\\label{"+label+"}\n\\end{table}\n")


def training_summary():
    import torch
    rows=[]
    for p in sorted((ROOT/"runs").glob("*/last.pt")):
        s=torch.load(p,map_location="cpu",weights_only=False)
        c=s["paper_config"]
        v=s["history"][-1]["validation_local"]
        m=json.loads(p.with_name("data_manifest.json").read_text())
        rows.append({"run":p.parent.name,"treatment":c["treatment"],"seed":c["seed"],"epoch":s["epoch"],"complete":s["complete"],
                     "parameters":s["parameters"],"updates":s["updates"],"training_rounds":m["training_rounds"],
                     "training_trajectories":m["trajectories"],"elapsed_seconds":s["elapsed_seconds"],
                     "train_seconds":sum(r["train_seconds"] for r in s["history"]),
                     "peak_gpu_bytes":max(r["gpu_peak_bytes"] for r in s["history"]),
                     "validation_participation":v["p_correct_rate"],"validation_candidate":v["c_correct_rate"],
                     "validation_commit":v["commit_correct_own_rate"],"validation_action":v["action_correct_teacher_rate"],
                     "initial_state_hash":s["initial_state_hash"],"data_hash":s["data_hash"],
                     "checkpoint_sha256":file_hash(p.with_name("epoch-120.pt")) if s["complete"] else file_hash(p)})
    frame=csv(OUTPUT/"training.csv",rows)
    if len(frame):
        display=frame[["treatment","seed","epoch","parameters","updates","validation_candidate","validation_commit"]].rename(
            columns={"treatment":"Model","seed":"Seed","epoch":"Epoch","parameters":"Params","updates":"Updates",
                     "validation_candidate":"Candidate","validation_commit":"COMMIT"})
        latex_table(display,PAPER/"tables/training.tex","Training progress and in-degree validation, with all seeds shown. Partial epochs are explicitly listed.","tab:training")
    audits=[]
    for seed in SEEDS:
        a,b=[ROOT/"runs"/f"{v}-s{seed}"/"last.pt" for v in ("normalized","raw_endpoints")]
        if not a.exists() or not b.exists():continue
        sa,sb=[torch.load(p,map_location="cpu",weights_only=False) for p in (a,b)]
        n=min(len(sa["history"]),len(sb["history"]))
        same_tapes=all(all(x[k]==y[k] for k in ("minibatch_order_hash","counterfactual_rng_start_hash","counterfactual_rng_end_hash"))
                       for x,y in zip(sa["history"][:n],sb["history"][:n]))
        ia,ib=[torch.load(p.with_name("initial.pt"),map_location="cpu",weights_only=False)["model_state_dict"] for p in (a,b)]
        tensor_equal=ia.keys()==ib.keys() and all(torch.equal(ia[k],ib[k]) for k in ia)
        audits.append({"seed":seed,"initial_tensors_exact_equal":tensor_equal,"data_hash_equal":sa["data_hash"]==sb["data_hash"],
                       "paired_epochs_verified":n,"orders_and_cf_tapes_equal":same_tapes,
                       "updates_normalized":sa["updates"],"updates_raw":sb["updates"],
                       "complete_both":sa["complete"] and sb["complete"],
                       "updates_equal_at_completion":sa["updates"]==sb["updates"] if sa["complete"] and sb["complete"] else None})
    csv(OUTPUT/"causal-isolation-audit.csv",audits)
    return frame


def case_summary():
    rows,rounds=[] ,[]
    for directory in sorted((ROOT/"evaluations").glob("*")):
        for p in sorted(directory.glob("*.json")):
            if p.stem in ("progress","complete"):continue
            value=json.loads(p.read_text())
            for r in value.pop("round_trace",[]):
                rounds.append({"label":value["label"],"case_id":value["case_id"],"degree":value["degree"],**r})
            value.pop("by_k",None)
            rows.append(value)
    frame=csv(OUTPUT/"cases.csv",rows)
    csv(OUTPUT/"round-traces.csv",rounds)
    return frame


def cell_summary(cases):
    rows=[]
    plan=pd.DataFrame(cohort_plan())
    keys=["tier","degree","n","family"]
    for p in sorted((ROOT/"models").glob("*.json")):
        spec=json.loads(p.read_text())
        subset=plan
        if spec["degree"] is not None:subset=subset[subset.degree==spec["degree"]]
        if spec["core_only"]:subset=subset[subset.tier=="core"]
        available=cases[cases.label==spec["label"]] if len(cases) else pd.DataFrame()
        for cell,group in subset.groupby(keys,sort=True):
            selected=available
            for key,value in zip(keys,cell):
                if len(selected):selected=selected[selected[key]==value]
            technical=int(selected.status.isin(["oom","timeout"]).sum()) if len(selected) else 0
            algorithm=selected[selected.status.isin(["ok","coloring_failure"])] if len(selected) else pd.DataFrame()
            n=len(algorithm)
            successes=int(algorithm.success.sum()) if n else 0
            random_graph=cell[-1]!="CLIQUE"
            lower=float(beta_distribution.ppf(.025,successes,n-successes+1)) if successes and random_graph else (0. if n and random_graph else None)
            upper=float(beta_distribution.ppf(.975,successes+1,n-successes)) if successes<n and random_graph else (1. if n and random_graph else None)
            row={"label":spec["label"],"kind":spec["kind"],"treatment":spec["treatment"],"selection":spec["selection"],"seed":spec["seed"],
                 **dict(zip(keys,cell)),"planned_cases":len(group),"completed":len(selected),"algorithmic_cases":n,
                 "technical_failures":technical,"unexecuted":len(group)-len(selected),"successes":successes,
                 "success_rate":successes/n if n else None,"cp95_lower":lower,"cp95_upper":upper,
                 "independent_random_graph_interval":random_graph,
                 "unsafe_commits":int(algorithm.unsafe_commits.sum()) if n else 0,
                 "mean_rounds":float(algorithm.rounds.mean()) if n else None,
                 "pending_nodes":int(algorithm.uncolored_nodes.sum()) if n else 0}
            for numerator in ("candidate_correct","forbidden_offers","commit_correct_own","valid_commits_rejected"):
                row[numerator+"_per_state"]=float(algorithm[numerator].sum()/max(1,algorithm.states.sum())) if n else None
            rows.append(row)
    return csv(OUTPUT/"cells.csv",rows)


def bootstrap_contrasts(cases,draws=2000):
    if not len(cases):return pd.DataFrame()
    base=cases[(cases.kind=="paper")&(cases.selection=="epoch120")&(cases.tier=="core")&
               cases.status.isin(["ok","coloring_failure"])]
    rows=[]
    rng=np.random.default_rng(20261021)
    for treatment in ("raw_endpoints","sum","mean","deepsets","transformer"):
        both=base[base.treatment.isin(["normalized",treatment])]
        for cell,group in both.groupby(["degree","n","family"],sort=True):
            pivot=group.pivot(index=["seed","graph_id"],columns="treatment",values="success")
            if not all(k in pivot for k in ("normalized",treatment)):continue
            paired=pivot.dropna(subset=["normalized",treatment])
            if not len(paired):continue
            paired=paired.astype(float)
            diff=(paired.normalized-paired[treatment]).unstack("graph_id")
            # The graph resample is shared across seeds: this is crossed data,
            # not an independent collection of seed-specific graph samples.
            diff=diff.dropna(axis=1)
            if diff.empty:continue
            values=diff.to_numpy()
            si=rng.integers(values.shape[0],size=(draws,values.shape[0]))
            gi=rng.integers(values.shape[1],size=(draws,values.shape[1]))
            samples=values[si[:,:,None],gi[:,None,:]].mean((1,2))
            lo,hi=np.quantile(samples,[.025,.975])
            rows.append({"reference":"normalized","control":treatment,"degree":cell[0],"n":cell[1],"family":cell[2],
                         "paired_training_seeds":values.shape[0],"shared_graphs":values.shape[1],"paired_executions":int(values.size),
                         "success_difference":float(values.mean()),"paired_bootstrap95_lower":float(lo),"paired_bootstrap95_upper":float(hi),
                         "bootstrap_draws":draws,"confirmatory_contrast":treatment in ("raw_endpoints","sum","mean"),
                         "pilot_only":values.shape[0]<5})
    return csv(OUTPUT/"paired-contrasts.csv",rows)


